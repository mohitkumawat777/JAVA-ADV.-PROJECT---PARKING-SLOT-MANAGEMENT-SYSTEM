    private void load_database() {
        try {
            Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/slot_status", "root", "root");

            PreparedStatement ps = con.prepareStatement("SELECT * FROM slots WHERE slot_status ='False'");
            ResultSet rs = ps.executeQuery();

            while (rs.next()) {
                String ss_number = rs.getString("slot_number");

                if (ss_number.equals("A-1")) {
                    slot_A1.setEnabled(false);
                }

                if (ss_number.equals("A-2")) {
                    slot_A2.setEnabled(false);
                }

                if (ss_number.equals("A-3")) {
                    slot_A3.setEnabled(false);
                }

                if (ss_number.equals("A-4")) {
                    slot_A4.setEnabled(false);
                }

                if (ss_number.equals("A-5")) {
                    slot_A5.setEnabled(false);
                }

                if (ss_number.equals("A-6")) {
                    slot_A6.setEnabled(false);
                }

                if (ss_number.equals("A-7")) {
                    slot_A7.setEnabled(false);
                }

                if (ss_number.equals("B-1")) {
                    slot_B1.setEnabled(false);
                }

                if (ss_number.equals("B-2")) {
                    slot_B2.setEnabled(false);
                }

                if (ss_number.equals("B-3")) {
                    slot_B3.setEnabled(false);
                }

                if (ss_number.equals("B-4")) {
                    slot_B4.setEnabled(false);
                }

                if (ss_number.equals("B-5")) {
                    slot_B5.setEnabled(false);
                }

                if (ss_number.equals("B-6")) {
                    slot_B6.setEnabled(false);
                }

                if (ss_number.equals("B-7")) {
                    slot_B7.setEnabled(false);
                }

            }

            rs.close();
            con.close();
        } catch (Exception e) {
            System.out.println(e);
        }
    }

